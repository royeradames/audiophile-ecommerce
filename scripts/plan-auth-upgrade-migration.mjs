// Plans the next account migration after a @royer/auth upgrade: applies every
// reviewed migration to an empty in-memory PostgreSQL, asks the vendored central
// adapter what it still needs, and writes only that as a new idempotent file.
// Nothing is applied to a real database and no issuer is contacted.
//
//   node scripts/plan-auth-upgrade-migration.mjs 0006_auth_rc5_callbacks.sql "0.1.0-rc.5"
import { writeFile, access } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";
import { createFederatedAuth } from "@royer/auth/federation";
import { getMigrations } from "better-auth/db/migration";
import pg from "pg";
import { applyMigrations, readMigrations } from "./migrations.mjs";

const [name, version] = process.argv.slice(2);
if (!/^\d{4}_[a-z0-9_]+\.sql$/.test(name ?? "") || !version) throw new Error("Usage: <NNNN_name.sql> <package version>");
const target = new URL(`../migrations/${name}`, import.meta.url);
if (await access(target).then(() => true, () => false)) throw new Error(`${name} exists; applied migrations are never rewritten.`);

const database = await PGlite.create();
const server = new PGLiteSocketServer({ db: database, host: "127.0.0.1", port: 0 });
await server.start();
const pool = new pg.Pool({ connectionString: `postgresql://postgres@${server.getServerConn()}/postgres?sslmode=disable`, max: 1 });
try {
  const client = await pool.connect();
  try { await applyMigrations(client, await readMigrations()); } finally { client.release(); }
  const auth = createFederatedAuth({
    appId: "audiophile",
    appName: "Audiophile",
    baseURL: "https://audiophile.example",
    secret: "migration-planning-only-secret-0123456789",
    database: pool,
    issuerURL: "https://issuer.example/api/auth",
    clientId: "migration-planning-only",
    clientSecret: "migration-planning-only",
  });
  const plan = await getMigrations(auth.engine.options);
  if (plan.unsafeChanges?.length || plan.schemaProblems?.length) throw new Error("The upgrade needs unsafe changes; plan them by hand.");
  if (!plan.toBeCreated.length && !plan.toBeAdded.length) {
    console.log(JSON.stringify({ planned: false, reason: "schema already current" }));
  } else {
    const sql = (await plan.compileMigrations())
      .replaceAll(/^create table "/gm, 'create table if not exists "')
      .replaceAll(/^create (unique )?index "/gm, (_match, unique) => `create ${unique ?? ""}index if not exists "`)
      .replaceAll(/ add column "/g, ' add column if not exists "');
    const header = `-- Generated by scripts/plan-auth-upgrade-migration.mjs for @royer/auth ${version} (central mode).\n` +
      "-- Additive only: what the upgraded adapter needs beyond the earlier migrations.\n\n";
    await writeFile(target, header + sql.trim() + "\n");
    console.log(JSON.stringify({
      planned: true, file: name,
      tables: plan.toBeCreated.map((table) => table.table),
      columns: plan.toBeAdded.map((table) => ({ table: table.table, columns: Object.keys(table.fields) })),
    }));
  }
} finally {
  await pool.end();
  await server.stop();
  await database.close();
}
