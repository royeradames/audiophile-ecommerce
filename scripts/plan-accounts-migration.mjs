// Writes migrations/0002_accounts.sql: the customer-account tables that the
// reviewed @royer/auth central adapter needs, planned against an empty
// in-memory PostgreSQL. Nothing is applied and no issuer is contacted.
// Statements are made idempotent so a rerun never fails or drops data.
import { access, writeFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";
import { createFederatedAuth } from "@royer/auth/federation";
import { getMigrations } from "better-auth/db/migration";
import pg from "pg";

// 0002 is applied and recorded by its hash; it is never rewritten. Upgrades use
// scripts/plan-auth-upgrade-migration.mjs, which writes a new file.
if (await access(new URL("../migrations/0002_accounts.sql", import.meta.url)).then(() => true, () => false)) {
  throw new Error("migrations/0002_accounts.sql exists; plan upgrades with scripts/plan-auth-upgrade-migration.mjs.");
}

const database = await PGlite.create();
const server = new PGLiteSocketServer({ db: database, host: "127.0.0.1", port: 0 });
await server.start();
const pool = new pg.Pool({ connectionString: `postgresql://postgres@${server.getServerConn()}/postgres?sslmode=disable`, max: 1 });
try {
  const auth = createFederatedAuth({
    appId: "audiophile",
    appName: "Audiophile",
    baseURL: "https://audiophile.example",
    secret: "migration-planning-only-secret-0123456789",
    database: pool,
    issuerURL: "https://issuer.example/api/auth",
    clientId: "migration-planning-only",
    clientSecret: "migration-planning-only",
  });
  const plan = await getMigrations(auth.engine.options);
  if (plan.toBeAdded.length || plan.unsafeChanges?.length || plan.schemaProblems?.length) {
    throw new Error("An empty database should only need new tables.");
  }
  const sql = (await plan.compileMigrations())
    .replaceAll(/^create table "/gm, 'create table if not exists "')
    .replaceAll(/^create (unique )?index "/gm, (_match, unique) => `create ${unique ?? ""}index if not exists "`);
  const header = "-- Generated by scripts/plan-accounts-migration.mjs from @royer/auth 0.1.0-rc.4 (central mode).\n" +
    "-- Customer accounts: local principals, sessions and the issuer link. No passwords live here.\n\n";
  await writeFile(new URL("../migrations/0002_accounts.sql", import.meta.url), header + sql.trim() + "\n");
  console.log(JSON.stringify({ planned: true, applied: false, tables: plan.toBeCreated.map((table) => table.table) }));
} finally {
  await pool.end();
  await server.stop();
  await database.close();
}
