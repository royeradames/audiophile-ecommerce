#!/usr/bin/env node
// setup-doctor: one manifest per app is the single source for its setup.
//   check  reads the Vercel project's env metadata (never values), checks each
//          key's kind (secret = Vercel "sensitive") and target, probes live URLs,
//          and prints the next step with its why, owner and deep link. Exit 1 if
//          anything required is wrong, so it can gate a deploy or run in CI.
//   guide  renders the same manifest as a Markdown how-to, so the human doc is
//          generated from the thing the check enforces and cannot drift from it.
//
//   node setup-doctor.mjs check setup.json [--target production]
//   node setup-doctor.mjs guide setup.json [--target production]
//   node setup-doctor.mjs check setup.json --env-json metadata.json   (tests: no Vercel call)
//
// Needs the Vercel CLI signed in to the manifest's scope. Prints no values.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { parseArgs } from "node:util";

const { positionals, values: options } = parseArgs({ allowPositionals: true, options: { target: { type: "string" }, "env-json": { type: "string" }, "no-probes": { type: "boolean", default: false } } });
const [command, manifestPath] = positionals;
if (!["check", "guide"].includes(command) || !manifestPath) {
  console.error("Usage: setup-doctor.mjs check|guide <manifest.json> [--target production|preview]");
  process.exit(2);
}
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const wanted = (targets) => targets.filter((t) => !options.target || t === options.target);
const settingsLink = `https://vercel.com/${manifest.scope}/${manifest.vercelProject}/settings/environment-variables`;
const addCommand = (key, target) =>
  `vercel env add ${key} ${target} --project ${manifest.vercelProject} --scope ${manifest.scope}` +
  (target === "development" ? "" : " --sensitive");

function humanSteps(item, target) {
  const steps = [...(item.get?.steps ?? [])];
  if (item.kind === "secret") steps.push(`In your own Terminal, not chat: \`${addCommand(item.key, target)}\`, then paste the value at its prompt. Don't use --value; it lands in shell history.`);
  else steps.push(`Set it on ${settingsLink} as a plain value for ${target}.`);
  return steps;
}

function listEnv() {
  const raw = options["env-json"] ? readFileSync(options["env-json"], "utf8") : execFileSync("vercel", ["api", `/v10/projects/${encodeURIComponent(manifest.vercelProject)}/env`, "--scope", manifest.scope, "--raw"],
    { stdio: ["ignore", "pipe", "pipe"] }).toString();
  // Keep metadata only; values never leave this function.
  return JSON.parse(raw).envs.map(({ key, type, target = [], gitBranch, securityIssues = [], contentHint }) =>
    ({ key, type, target, gitBranch, securityIssues, integration: contentHint?.type === "integration-store-secret" }));
}

async function probe(item) {
  try {
    const response = await fetch(item.url, { redirect: "manual", signal: AbortSignal.timeout(10000) });
    return { ok: item.expect.includes(response.status), status: response.status };
  } catch (error) { return { ok: false, status: error.name }; }
}

if (command === "guide") {
  const lines = [`# Set up ${manifest.app}${options.target ? ` (${options.target})` : ""}`, "", manifest.explain, "",
    `Generated by setup-doctor from \`${manifestPath}\`. Edit the manifest, not this text. Verify: \`node setup-doctor.mjs check ${manifestPath}\`.`, ""];
  const human = manifest.env.flatMap((item) => wanted(item.target).filter(() => item.owner === "human").map((target) => ({ item, target })));
  const agent = manifest.env.filter((item) => item.owner === "agent" && wanted(item.target).length);
  lines.push("## Your steps", "");
  human.forEach(({ item, target }, index) => {
    lines.push(`### ${index + 1}. ${item.key} for ${target} (${item.kind})`, "", `Why you: ${item.whyHuman}`, "", `What it is: ${item.why}`, "");
    if (item.learn) lines.push(`Learn: ${item.learn}`, "");
    humanSteps(item, target).forEach((step, n) => lines.push(`${n + 1}. ${step}`));
    lines.push("");
  });
  if (!human.length) lines.push("None. The agent does everything.", "");
  lines.push("## The agent does", "", ...agent.map((item) => `- \`${item.key}\` (${item.kind}, ${wanted(item.target).join(" + ")}): ${item.why}`), "");
  console.log(lines.join("\n"));
  process.exit(0);
}

let failures = 0;
const env = listEnv();
const mark = (ok) => (ok ? "ok  " : "FAIL");
console.log(`${manifest.app}: Vercel project ${manifest.vercelProject} (${manifest.scope})\n`);
for (const item of manifest.env) {
  for (const target of wanted(item.target)) {
    const found = env.find((entry) => entry.key === item.key && entry.target.includes(target) && !entry.gitBranch);
    let problem = null;
    if (!found) problem = "missing";
    // Vercel can't store Development values as Sensitive, so a readable Development secret is expected.
    else if (item.kind === "secret" && target !== "development" && found.type !== "sensitive") problem = `readable (${found.type}); a secret must be Sensitive. Remove and re-add it`;
    if (problem) failures++;
    const note = found?.type === "sensitive" && item.kind === "config" ? " (stored write-only; you can't read it back to check it)" : "";
    console.log(`${mark(!problem)} ${item.key} [${target}] ${item.kind}${problem ? ": " + problem : note}`);
    if (!problem) continue;
    console.log(`     Why it exists: ${item.why}`);
    if (item.owner === "agent") { console.log(`     Owner: agent. ${item.agentFix}`); continue; }
    console.log(`     Owner: Royer. Why you: ${item.whyHuman}`);
    if (item.learn) console.log(`     Learn: ${item.learn}`);
    humanSteps(item, target).forEach((step, n) => console.log(`     ${n + 1}. ${step}`));
  }
}
const accepted = new Set(manifest.env.filter((item) => item.acceptReadable).map((item) => item.key));
const readable = env.filter((entry) => entry.securityIssues.includes("readable-secret") && !accepted.has(entry.key) &&
  (!options.target || entry.target.includes(options.target)));
const integrationReadable = readable.filter((entry) => entry.integration);
const ownReadable = readable.filter((entry) => !entry.integration);
for (const entry of ownReadable) { failures++; console.log(`FAIL ${entry.key} [${entry.target.join("+")}]: Vercel flags it as a readable secret. Re-add it as Sensitive, or mark it acceptReadable with a reason.`); }
if (integrationReadable.length) console.log(`info ${integrationReadable.length} integration-managed values are readable secrets (Vercel's flag). The integration owns them; open ${settingsLink} to review.`);
for (const item of options["no-probes"] ? [] : manifest.probes ?? []) {
  if (options.target && item.target !== options.target) continue;
  const result = await probe(item);
  if (!result.ok) failures++;
  console.log(`${mark(result.ok)} probe ${item.name}: ${item.url} -> ${result.status} (expected ${item.expect.join(" or ")})${result.ok ? "" : ". " + item.ifFails}`);
}
console.log(failures ? `\n${failures} to fix. Rerun after each step.` : "\nAll set.");
process.exit(failures ? 1 : 0);
